import assert from 'node:assert/strict';
import { readFile, readdir, stat } from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const text=p=>readFile(new URL(p,root),'utf8');
const config=JSON.parse(await text('wrangler.jsonc'));
assert.equal(config.name,'hacker-tube');
assert.ok(config.routes.some(r=>r.pattern==='hacker-tube.org'&&r.custom_domain));
assert.equal(config.assets.not_found_handling,'none');
assert.equal(config.main,'cloudflare/worker.js');
assert.equal(config.assets.binding,'ASSETS');
const html=await text('dist/client/index.html');
assert.ok(html.includes('<title>HackerTube'));
assert.ok(html.includes('rel="canonical"'));
assert.ok(html.includes('property="og:image"'));
assert.ok(html.includes('Picked by'));
assert.ok(!html.includes('noindex'));
const assets=await readdir(new URL('dist/client/assets/',root));
const js=(await Promise.all(assets.filter(f=>f.endsWith('.js')).map(f=>text('dist/client/assets/'+f)))).join('\n');
assert.ok(js.includes('HackerTube home'));
assert.ok(!js.includes('PickedTube'));
assert.ok(js.includes('https://i.ytimg.com/vi/'));
assert.ok(js.includes('hq2.jpg')&&js.includes('hqdefault.jpg'));
assert.ok(!js.includes('/thumbs/'));
assert.ok(js.includes('youtube-nocookie.com/embed/'));
assert.ok(!/CLOUDFLARE_API_TOKEN|Bearer\s+[a-zA-Z0-9_-]{20}/.test(js));
assert.ok((await text('dist/client/.assetsignore')).includes('/thumbs/**'));
let count=0,maxSize=0;
async function walk(url){for(const e of await readdir(url,{withFileTypes:true})){if(e.name==='thumbs')continue;const u=new URL(e.name+(e.isDirectory()?'/':''),url);if(e.isDirectory())await walk(u);else {count++;maxSize=Math.max(maxSize,(await stat(u)).size);}}}
await walk(new URL('dist/client/',root));
assert.ok(count<20000);assert.ok(maxSize<25*1024*1024);
console.log(JSON.stringify({status:'passed',domain:config.routes[0].pattern,files:count,largestFileBytes:maxSize,imageDelivery:'YouTube direct',videoDelivery:'YouTube embed'}));
